export type MessageKey = keyof (typeof DICTIONARY)["en"];

let currentLocale: Locale = "zh-CN";

export function setLocale(locale: string) {
  if (locale === "zh-TW" || locale === "zh-HK") {
    currentLocale = "zh-TW";
  } else if (locale.startsWith("zh")) {
    currentLocale = "zh-CN";
  } else {
    currentLocale = "en";
  }
}

export function t(key: MessageKey, params?: Record<string, string | number>): string {
  const dict = DICTIONARY[currentLocale] || DICTIONARY["zh-CN"];
  let str: string = dict[key] || DICTIONARY["zh-CN"][key] || key;
  if (params) {
    for (const [k, v] of Object.entries(params)) {
      str = str.replace(new RegExp(`\\{${k}\\}`, "g"), String(v));
    }
  }
  return str;
}

export function getDefaultTopic(): string {
  return t("topicDefault");
}

export function getPresetTopics(): string[] {
  return [
    t("topicPreset1"),
    t("topicPreset2"),
    t("topicPreset3"),
    t("topicPreset4"),
    t("topicPreset5"),
  ];
}
